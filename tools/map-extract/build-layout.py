BADGE = {"🚩": "flag", "🚁": "sword", "💙": "heart-blue", "💖": "heart-red", "❤": "heart-red", "🤍": "heart-white", "✚": "plus"}
TIER = re.compile(r"^\(([A-Z+]+)\)")


def parse(line: str):
    s = line.strip()
    tier = None
    m = TIER.match(s)
    if m:
        tier, s = m.group(1), s[m.end():].strip()
    # 요약은 "공백 + (" 로 시작하는 마지막 괄호. 이름에 붙은 괄호("니카(루초)")는 이름의 일부.
    note = ""
    i = s.rfind(" (")
    if i >= 0 and s.endswith(")"):
        note, s = s[i + 2 : -1].strip(), s[:i].rstrip()
    # 뒤쪽 배지 문자들 분리
    badges = []
    s = s.replace("️", "")  # ❤️ 의 변형 선택자 제거
    while s and s[-1] in BADGE:
        badges.insert(0, BADGE[s[-1]])
        s = s[:-1].rstrip()
    return tier, s.strip(), badges, note


